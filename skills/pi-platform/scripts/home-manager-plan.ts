#!/usr/bin/env node
// Usage: node home-manager-plan.ts --repo CONFIG_REPO --platform PLATFORM_REPO [--out FILE] [--dry-run]
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { gitText, parseArgs, required, safeRelative, safeRepo, writeNewFile } from "./lib-policy.ts";

export interface HomeManagerPlan {
  schemaVersion: 1;
  configRepo: string;
  platformRepo: string;
  flakeFiles: string[];
  moduleCandidates: string[];
  flakeHomeManagerDeclarations: string[];
  generatedFlakes: string[];
  status: "ready-to-review" | "missing-module-location" | "ambiguous-module-location";
  recommendation: string;
  edits: Array<{
    file: string;
    action: "review-import-or-module-registration" | "review-read-only-composition";
    details: string;
  }>;
}
function trackedFiles(repo: string): string[] {
  return gitText(repo, ["ls-files", "-z", "--cached", "--others", "--exclude-standard"])
    .split("\0")
    .filter(Boolean)
    .map((p) => safeRelative(repo, p))
    .filter((p): p is string => p !== undefined);
}
export function makeHomeManagerPlan(configInput: string, platformInput: string): HomeManagerPlan {
  const configRepo = safeRepo(configInput);
  const platformRepo = safeRepo(platformInput);
  const files = trackedFiles(configRepo).sort();
  const flakes = files.filter((file) => file === "flake.nix" || file.endsWith("/flake.nix"));
  const contents = new Map(
    files.filter((file) => file.endsWith(".nix")).map((file) => [file, readFileSync(join(configRepo, file), "utf8")]),
  );
  const candidates = [...contents]
    .filter(
      ([file, text]) =>
        !file.endsWith("flake.nix") &&
        (file.startsWith("packages/agents/pi/") ||
          /homeManagerModules|home-manager|home\.activation|programs\.home-manager|home-manager\.users|flake\.modules\.homeManager/.test(
            text,
          )),
    )
    .map(([file]) => file);
  const declarations = flakes.flatMap((file) =>
    [
      ...(contents.get(file) ?? "").matchAll(
        /(?:inputs\.[A-Za-z0-9_.-]+\s*=|flake-file\.inputs(?:\.[A-Za-z0-9_.-]+)?\s*=|flake\.modules\.homeManager(?:\.[A-Za-z0-9_-]+)?\s*=|homeManager\s*=|homeManagerModules\s*=)[^;\n]*/g,
      ),
    ].map((match) => `${file}: ${match[0].trim()}`),
  );
  const generatedFlakes = flakes.filter((file) =>
    /generated by pi-platform|platform scaffold/i.test(contents.get(file) ?? ""),
  );
  const status =
    candidates.length === 0
      ? "missing-module-location"
      : candidates.length > 1
        ? "ambiguous-module-location"
        : "ready-to-review";
  const recommendation =
    status === "missing-module-location"
      ? "No clear Home Manager module location was found; choose a configuration module explicitly before integrating."
      : status === "ambiguous-module-location"
        ? "Several possible module files exist; review all candidates with the owner and choose the intended module."
        : "Review the module and import chain; do not assume flake.nix is editable or activate the configuration.";
  const edits: HomeManagerPlan["edits"] = candidates.map((file) => ({
    file,
    action: "review-import-or-module-registration",
    details: "Review whether this existing module should import the platform's generated read-only module.",
  }));
  edits.push({
    file: "platform JSON catalog",
    action: "review-read-only-composition",
    details: `Compose documented catalog/options read-only from ${relative(configRepo, platformRepo)}; this is guidance, not a production scope resolver.`,
  });
  return {
    schemaVersion: 1,
    configRepo: ".",
    platformRepo: ".",
    flakeFiles: flakes,
    moduleCandidates: candidates,
    flakeHomeManagerDeclarations: declarations,
    generatedFlakes,
    status,
    recommendation,
    edits,
  };
}
export function runHomeManagerPlan(argv: string[]): HomeManagerPlan | { dryRun: true; output: string } {
  const args = parseArgs(argv, ["repo", "platform", "out"], ["dry-run"]);
  const plan = makeHomeManagerPlan(required(args, "repo"), required(args, "platform"));
  const out = args.get("out");
  if (typeof out === "string") {
    writeNewFile(out, `${JSON.stringify(plan, null, 2)}\n`, args.has("dry-run"));
    if (args.has("dry-run")) return { dryRun: true, output: relative(process.cwd(), out) };
  }
  return plan;
}
export function main(argv = process.argv.slice(2)): void {
  if (argv.includes("--help"))
    return void process.stdout.write(
      "Usage: home-manager-plan.ts --repo CONFIG_REPO --platform PLATFORM_REPO [--out FILE] [--dry-run]\n",
    );
  try {
    process.stdout.write(`${JSON.stringify(runHomeManagerPlan(argv), null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`home-manager-plan: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
if (import.meta.url === `file://${process.argv[1]}`) main();
